"""Extra pages built by teammates — one file per page, so nobody edits app.py.

Each page module defines:
    TITLE = "Head to head"      # name shown in the sidebar
    READY = False               # set to True when the page is ready to show
    def show(history): ...      # draws the page; `history` is the log with derived metrics

A page only appears in the sidebar once its READY is True, and a page that fails to
import is skipped with a warning instead of breaking the whole app.
DO NOT EDIT THIS FILE — edit only your own page module.
"""

import importlib
import logging

_MODULES = ["head_to_head", "trip_planner", "business"]


def load_pages():
    """(pages that are READY, names of modules that failed to import)."""
    ready, broken = [], []
    for name in _MODULES:
        try:
            module = importlib.import_module(f"{__name__}.{name}")
        except Exception:                      # a teammate's bug must not stop the app
            logging.exception("Could not import page %s", name)
            broken.append(name)
            continue
        if getattr(module, "READY", False):
            ready.append(module)
    return ready, broken
